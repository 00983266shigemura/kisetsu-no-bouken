'use strict';
const assert=require('assert');
const S=require('./execution-state.cjs');
const id='release_123',sha='a'.repeat(40),now='2026-10-10T00:00:00Z';
const s=S.initial(id,sha,1,now);
const serialized=S.wire(s);assert.deepStrictEqual(S.unwrap(serialized),s);
assert.throws(()=>S.unwrap(serialized.replace('RUNNING','VERIFIED')),/HASH_MISMATCH/);
assert.throws(()=>S.transition(s,'RESTART',{attempt:2,expectedVersion:0,expectedFence:1,now}),/VERSION_CONFLICT/);
assert.throws(()=>S.transition(s,'RESTART',{attempt:2,expectedVersion:1,expectedFence:0,now}),/STALE_WRITER/);
assert.throws(()=>S.transition(s,'RESTART',{attempt:1,expectedVersion:1,expectedFence:1,now}),/REPLAY_ATTEMPT_NOT_NEW/);
const retry=S.transition(s,'RESTART',{attempt:2,expectedVersion:1,expectedFence:1,now});
assert.equal(retry.fence,2);
assert.throws(()=>S.transition(retry,'COMPLETE',{attempt:1,expectedVersion:2,expectedFence:1,now,evidence:{release_id:'b'.repeat(64)}}),/STALE_WRITER/);
const complete=S.transition(retry,'COMPLETE',{attempt:2,expectedVersion:2,expectedFence:2,now,evidence:{release_id:'b'.repeat(64)}});
assert.equal(complete.phase,'VERIFIED');
assert.strictEqual(S.transition(complete,'COMPLETE',{attempt:2,expectedVersion:3,expectedFence:2,now}),complete);
assert.throws(()=>S.recover(complete,()=>false),/EVIDENCE_NOT_FOUND/);
S.recover(S.unwrap(S.wire(complete)),e=>e.release_id==='b'.repeat(64));
const block=S.transition(s,'BLOCK',{attempt:1,expectedVersion:1,expectedFence:1,now});
assert.throws(()=>S.transition(block,'RESTART',{attempt:2,expectedVersion:2,expectedFence:1,now}),/BLOCKED_NOT_RETRYABLE/);
assert.throws(()=>S.initial('../bad',sha,1,now),/invalid identifier/);
assert.throws(()=>S.initial(id,'wrong',1,now),/invalid identifier/);
assert.equal(S.digest('abc'),'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
console.log('PASS: execution checkpoint integrity, version CAS, fencing, replay and fault injection');
